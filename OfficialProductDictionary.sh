# ── Helper: abort if expected product file is missing ─────────────────────────
assert_product_exists() {
    local f="$1"
    if [[ ! -f "$f" ]]; then
        echo "ERROR: production ROOT not found: $f" >&2
        return 1
    fi
}
export -f assert_product_exists
